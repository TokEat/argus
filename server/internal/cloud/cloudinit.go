package cloud

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"text/template"
)

// ============================================================================
// Cloud-Init 模板引擎
//
// 将伸缩策略中配置的 UserDataTemplate 渲染为实际的 Cloud-Init 脚本，
// 注入 Server 地址、Agent ID、租户 ID 等运行时参数。
// ============================================================================

// CloudInitVars 模板变量集合
type CloudInitVars struct {
	ServerAddr  string // Server gRPC 地址，如 10.0.0.1:50051
	APIURL      string // Server HTTP API 地址，如 http://10.0.0.1:8085
	AgentID     string // 预分配的 Agent ID
	TenantID    string // 租户 ID
	Tags        string // 逗号分隔的标签字符串
	PSK         string // Agent 预共享密钥
	DownloadURL string // Agent 二进制下载地址（OSS 预签名 URL 或 Server HTTP URL）
}

// DefaultCloudInitTemplate 默认 Cloud-Init 模板
const DefaultCloudInitTemplate = `#!/bin/bash
set -ex

# Argus Agent Auto-Provisioning Script
# Generated by Argus Cloud Scheduler

echo "[Argus] Starting agent provisioning..."

# 下载 Agent 二进制（优先使用 OSS 预签名 URL，fallback 到 Server HTTP）
DOWNLOAD_URL="{{.DownloadURL}}"
AGENT_BIN="/usr/local/bin/dddd-agent"

for i in 1 2 3 4 5; do
    if curl -fsSL "$DOWNLOAD_URL" -o "$AGENT_BIN"; then
        chmod +x "$AGENT_BIN"
        echo "[Argus] Agent binary downloaded successfully"
        break
    fi
    echo "[Argus] Download attempt $i failed, retrying in 10s..."
    sleep 10
done

if [ ! -x "$AGENT_BIN" ]; then
    echo "[Argus] FATAL: Failed to download agent binary after 5 attempts"
    exit 1
fi

# 创建日志目录
mkdir -p /var/log/argus

# 注册为 systemd 服务（确保 OS 重启或进程崩溃后自动恢复）
cat > /etc/systemd/system/argus-agent.service <<EOF
[Unit]
Description=Argus Scanning Agent
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=$AGENT_BIN \
    --server "{{.ServerAddr}}" \
    --id "{{.AgentID}}" \
    --api "{{.APIURL}}" \
    --tags "cloud,auto-scaled" \
    --spot{{if .PSK}} \
    --psk "{{.PSK}}"{{end}}
Restart=always
RestartSec=5
StandardOutput=append:/var/log/argus/agent.log
StandardError=append:/var/log/argus/agent.log
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable argus-agent
systemctl start argus-agent

echo "[Argus] Agent registered as systemd service and started"
`

// RenderCloudInit 将模板渲染为最终的 Cloud-Init 脚本。
// 如果 tmpl 为空，使用默认模板。
func RenderCloudInit(tmpl string, vars CloudInitVars) (string, error) {
	if tmpl == "" {
		tmpl = DefaultCloudInitTemplate
	}

	t, err := template.New("cloudinit").Parse(tmpl)
	if err != nil {
		return "", fmt.Errorf("parse cloud-init template: %w", err)
	}

	var buf bytes.Buffer
	if err := t.Execute(&buf, vars); err != nil {
		return "", fmt.Errorf("execute cloud-init template: %w", err)
	}

	return buf.String(), nil
}

// RenderCloudInitBase64 渲染模板并返回 Base64 编码结果（阿里云 UserData 要求 Base64）。
func RenderCloudInitBase64(tmpl string, vars CloudInitVars) (string, error) {
	script, err := RenderCloudInit(tmpl, vars)
	if err != nil {
		return "", err
	}
	return base64.StdEncoding.EncodeToString([]byte(script)), nil
}
